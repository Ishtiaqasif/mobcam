using System;
using System.Diagnostics;
using System.IO;
using System.Windows;
using System.Windows.Media;
using System.Windows.Navigation;

namespace MobCam;

/// <summary>Version, privacy summary, links and the third-party licences.</summary>
public partial class AboutWindow : Window
{
    /// <summary>Same promise as README → Privacy and PRIVACY.md.</summary>
    private const string PrivacySummary =
        "No accounts, no analytics, no ads, no servers. The video goes from your phone to this PC, over " +
        "the USB cable or your local network, and is never recorded or sent anywhere else. The only time " +
        "MobCam goes online is to ask GitHub for the latest version number, and only if you allow it. " +
        "Pairings and settings stay on your devices.";

    /// <summary>Written next to MobCam.exe by scripts/notices.ps1 for release builds.</summary>
    private const string NoticesFile = "THIRD-PARTY-NOTICES.txt";

    public AboutWindow(ImageSource icon)
    {
        InitializeComponent();
        Icon = icon;
        LogoImage.Source = icon;
        VersionText.Text = $"Version {BuildInfo.Label}";
        PrivacyText.Text = PrivacySummary;
        NoticesBox.Text = LoadNotices();
    }

    private static string LoadNotices()
    {
        try
        {
            return File.ReadAllText(Path.Combine(AppContext.BaseDirectory, NoticesFile));
        }
        catch (IOException)
        {
            // Development builds use the installed .NET runtime and ship nothing else third-party.
            return "This build doesn't include the licence list; the installer does.\n" +
                   "It is generated by scripts/notices.ps1 in the source code.";
        }
        catch (UnauthorizedAccessException)
        {
            return $"Could not read {NoticesFile}.";
        }
    }

    private void OnLink(object sender, RequestNavigateEventArgs e)
    {
        Process.Start(new ProcessStartInfo(e.Uri.AbsoluteUri) { UseShellExecute = true });
        e.Handled = true;
    }

    private void OnClose(object sender, RoutedEventArgs e) => Close();
}
